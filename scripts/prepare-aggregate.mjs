#!/usr/bin/env node
/**
 * Generate the installable aggregate patch from `patches/aggregate.yaml`.
 *
 * Why a generator instead of a literal `optional: true` patch: DSH's Loader
 * has no optional-row semantics — a row naming a missing package becomes a
 * failed fiber. This script resolves each declared package in the target
 * profile and writes only the rows that exist, which is the equivalent
 * "skip missing, keep the rest" behavior, without touching the plugins.
 *
 * Usage:
 *   node scripts/prepare-aggregate.mjs
 *   node scripts/prepare-aggregate.mjs --profile C:\\Users\\me\\.dsh\\profiles\\desktop
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(here, '..');
const sourcePath = path.join(projectRoot, 'patches', 'aggregate.yaml');
const targetPath = path.join(projectRoot, 'aggregate', 'cordis.patch.yml');

/** Read `--profile <dir>` or fall back to the desktop profile. */
function profileDir() {
  const index = process.argv.indexOf('--profile');
  if (index !== -1 && process.argv[index + 1] !== undefined) {
    return path.resolve(process.argv[index + 1]);
  }
  return process.env.DSH_PROFILE_DIR
    ?? path.join(process.env.USERPROFILE ?? process.env.HOME ?? '.', '.dsh', 'profiles', 'desktop');
}

/**
 * Parse the small declarative manifest without adding a YAML dependency.
 * The file is intentionally restricted to `insert` rows with id/name/optional.
 * @param {string} text
 */
export function parseAggregateManifest(text) {
  const rows = [];
  let current = null;
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (line.startsWith('- id:')) {
      if (current !== null) rows.push(current);
      current = { id: line.slice('- id:'.length).trim(), name: '', optional: false };
      continue;
    }
    if (current === null) continue;
    if (line.startsWith('name:')) {
      current.name = line.slice('name:'.length).trim();
      continue;
    }
    if (line === 'optional: true') current.optional = true;
  }
  if (current !== null) rows.push(current);
  return rows.filter(row => row.id.length > 0 && row.name.length > 0);
}

/**
 * Whether a package resolves from the target profile.
 * @param {string} profile
 * @param {string} packageName
 */
export function isInstalled(profile, packageName) {
  try {
    const requireFromProfile = createRequire(path.join(profile, 'package.json'));
    requireFromProfile.resolve(`${packageName}/package.json`);
    return true;
  } catch {
    return false;
  }
}

/**
 * Build the patch text for a set of rows.
 * @param {{ id: string, name: string }[]} rows
 */
export function renderPatch(rows) {
  const lines = [
    '# Generated by `node scripts/prepare-aggregate.mjs`.',
    '# Only rows whose packages resolved in the profile at generation time are',
    '# present. Regenerate after installing or removing a compatible plugin.',
    '- insert:',
  ];
  for (const row of rows) {
    lines.push(`    - id: ${row.id}`, `      name: ${row.name}`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Select the rows an aggregate install should insert.
 *
 * Memweave itself is provided by the standalone bundle; re-inserting the same
 * Loader id from the aggregate would be a duplicate entry id. The aggregate is
 * therefore additive: installed optional plugins plus the marker row.
 * @param {{ id: string, name: string, optional: boolean }[]} declared
 * @param {string} profile
 * @returns {{ included: object[], skipped: object[], provided: object[] }}
 */
export function selectAggregateRows(declared, profile) {
  const included = [];
  const skipped = [];
  const provided = [];
  for (const row of declared) {
    if (row.name === 'dsh-memweave') {
      provided.push(row);
      continue;
    }
    if (!row.optional) {
      included.push(row);
      continue;
    }
    if (isInstalled(profile, row.name)) included.push(row);
    else skipped.push(row);
  }
  if (!included.some(row => row.name === 'dsh-memweave-aggregate')) {
    included.push({ id: 'memweave-aggregate', name: 'dsh-memweave-aggregate' });
  }
  return { included, skipped, provided };
}

async function main() {
  const profile = profileDir();
  const source = await fs.readFile(sourcePath, 'utf8');
  const declared = parseAggregateManifest(source);
  const { included, skipped, provided } = selectAggregateRows(declared, profile);
  await fs.mkdir(path.dirname(targetPath), { recursive: true });
  await fs.writeFile(targetPath, renderPatch(included), 'utf8');
  console.log(`profile: ${profile}`);
  console.log(`wrote:   ${targetPath}`);
  console.log(`provided by standalone (${provided.length}): ${provided.map(row => row.name).join(', ') || 'none'}`);
  console.log(`included (${included.length}): ${included.map(row => row.name).join(', ') || 'none'}`);
  console.log(`skipped  (${skipped.length}): ${skipped.map(row => row.name).join(', ') || 'none'}`);
}

if (process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
